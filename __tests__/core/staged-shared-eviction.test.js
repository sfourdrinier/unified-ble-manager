test('a commit hook receives extra ownership before any eviction cleanup reenters', () => {
  const quota = new AggregateStreamQuota(30)
  const source = new CoreBoundedStream(limits(), 'error')
  const target = new CoreBoundedStream(limits(), 'drop-oldest')
  quota.register(source); quota.register(target)
  let presence
  let observed
  target.stageOwned({ value: 'old', release() { observed = presence.value } }, 4, identity).publish()
  quota.emit(source, 'new', 4)
  const stage = target.reserveOwnedReplacement(4, identity, identity)
  const extras = quota.replaceSharedClaim(source, source.claimConsumer().claim(), 'new', 4, 1, [stage], 1, undefined, refs => { presence = refs[0] })
  expect(observed).toBe('new')
  expect(extras[0]).toBe(presence)
  presence.release()
})

test('a throwing commit hook still settles every queue and reports the extra references', async () => {
  const quota = new AggregateStreamQuota(30)
  const source = new CoreBoundedStream(limits(), 'error')
  const target = new CoreBoundedStream(limits(), 'drop-oldest')
  quota.register(source); quota.register(target)
  const release = jest.fn()
  target.stageOwned({ value: 'old', release }, 4, identity).publish()
  quota.emit(source, 'new', 4)
  const stage = target.reserveOwnedReplacement(4, identity, identity)
  let failure
  try {
    quota.replaceSharedClaim(source, source.claimConsumer().claim(), 'new', 4, 1, [stage], 1, undefined, () => { throw new Error('hook failed') })
  } catch (error) { failure = error }
  expect(failure.cause.message).toBe('hook failed')
  expect(release).toHaveBeenCalledTimes(1)
  expect(failure.references[0].value).toBe('new')
  const reader = target[Symbol.asyncIterator]()
  expect((await reader.next()).value.kind).toBe('overflow')
  expect((await reader.next()).value.value).toBe('new')
  failure.references[0].release()
  expect(quota.retainedBytes()).toBe(2)
})

