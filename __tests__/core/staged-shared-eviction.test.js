  expect(failure.references).toHaveLength(1)
  expect(observed.quota).toBe(11)
  expect(observed.counters.droppedItems).toBe(1)
  for (const stream of [left, right]) {
    const reader = stream[Symbol.asyncIterator]()
    expect((await reader.next()).value.kind).toBe('overflow')
    expect((await reader.next()).value.value).toBe('new')
  }
  failure.references[0].release()
  expect(quota.retainedBytes()).toBe(3)
