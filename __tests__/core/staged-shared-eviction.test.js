  const right = new CoreBoundedStream(limits(), 'drop-oldest')
  for (const stream of [source, left, right]) quota.register(stream)
  let observed
  left.stageOwned({ value: 'old', release() {
    observed = { quota: quota.retainedBytes(), counters: right.overflowCounters() }
    throw new Error('old cleanup')
  } }, 4, identity).publish()
  right.emit('old right', 4)
  quota.emit(source, 'new', 4)
  const a = left.reserveOwnedReplacement(4, identity, identity)
  const b = right.reserveOwnedReplacement(4, identity, identity)
