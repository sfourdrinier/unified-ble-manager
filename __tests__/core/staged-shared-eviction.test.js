test('tracking view control reservations cannot exceed aggregate quota and released views free admission', async () => {
  const quota = new AggregateStreamQuota(3)
  const source = new CoreBoundedStream(limits(), 'error')
  quota.register(source)
  const first = new CoreBoundedStream(limits(), 'error')
  const second = new CoreBoundedStream(limits(), 'error')
  const third = new CoreBoundedStream(limits(), 'error')
  source.trackRetainedView(first)
  source.trackRetainedView(second)
  expect(() => source.trackRetainedView(third)).toThrow()
  expect(quota.retainedBytes()).toBe(3)
  await first.close()
  // A closed view still owns its terminal until the reader consumes it.
  expect((await first[Symbol.asyncIterator]().next()).value.kind).toBe('terminal')
  source.trackRetainedView(third)
  expect(quota.retainedBytes()).toBe(3)
  await second.close()
  await third.close()
  await source.close()
})

test.each([
  ['drop-oldest', ['notice', 'new']],
  ['drop-newest', ['old', 'notice']]
])('ordered replacement applies %s to each item and rolls back quota refusal', async (policy, expected) => {
  const quota = new AggregateStreamQuota(15)
  const source = new CoreBoundedStream(limits(2), 'error')
  const target = new CoreBoundedStream(limits(2), policy)
  quota.register(source); quota.register(target)
  quota.emit(target, 'old', 4)
  quota.emit(source, 'new', 4)
  const claim = source.claimConsumer().claim()
  const stage = target.reserveOwnedReplacementBatch([
    { byteLength: 4, project: () => 'notice', copy: identity },
    { byteLength: 4, project: identity, copy: identity }
  ])
  expect(quota.replaceSharedClaim(source, claim, 'new', 20, 1, [stage])).toBeNull()
  expect(quota.replaceSharedClaim(source, claim, 'new', 6, 1, [stage])).toEqual([])
  const reader = target[Symbol.asyncIterator]()
  expect((await reader.next()).value.kind).toBe('overflow')
  const first = (await reader.next()).value.value
  expect(quota.retainedBytes()).toBeGreaterThan(2)
  const second = (await reader.next()).value.value
  expect([first, second]).toEqual(expected)
  expect(quota.retainedBytes()).toBe(2)
})

