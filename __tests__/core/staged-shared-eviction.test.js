test.each(['cache-first', 'readers-first'])('shared backing allocation survives %s release order', async order => {
  const quota = new AggregateStreamQuota(40)
  const source = new CoreBoundedStream(limits(), 'error')
  quota.register(source)
  const cache = source.createRetainedByteAdmission()
  const backing = new Uint8Array(12)
  const views = [backing.subarray(0, 4), backing.subarray(4, 8)]
  quota.emit(source, views, 1, null, 0, 16)
  const claim = source.claimConsumer().claim()
  const refs = quota.replaceSharedClaim(source, claim, views, 4, 2, [], 2,
    { admission: cache, bytes: 3, buffers: [views[0].buffer, views[1].buffer], valueBuffers: [backing.buffer] })
  expect(quota.retainedBytes()).toBe(24)
  if (order === 'cache-first') {
    expect(cache(0, [])).toBe(true)
    expect(quota.retainedBytes()).toBe(21)
    refs[0].release()
    expect(quota.retainedBytes()).toBe(19)
    refs[1].release()
  } else {
    refs[1].release()
    expect(quota.retainedBytes()).toBe(22)
    refs[0].release()
    expect(quota.retainedBytes()).toBe(16)
    expect(cache(0, [])).toBe(true)
  }
  expect(quota.retainedBytes()).toBe(1)
  await source.close()
})

