const { CoreBoundedStream } = require('../../src/core/bounded-stream')
const { AggregateStreamQuota } = require('../../src/core/aggregate-stream-quota')
const { resourceCount } = require('../../src/backend-contract/primitives')

const limits = { itemCapacity: resourceCount(3), byteCapacity: resourceCount(21), reservedControlCapacity: resourceCount(1) }

test('delivery and retained sizes are independent through admission, claims and removal', async () => {
  const stream = new CoreBoundedStream(limits, 'error', true)
  const quota = new AggregateStreamQuota(100)
  quota.register(stream)
  expect(quota.emit(stream, 'first', 10, null, 0, 80).accepted).toBe(true)
  expect(quota.retainedBytes()).toBe(81)
  const reader = stream.claimConsumer()
  const claim = reader.claim()
  expect(stream.claimedBytes(claim)).toBe(80)
  claim.rollback()
  expect(quota.emit(stream, 'second', 10, null, 0, 25).terminated).toBe(true)
  expect(quota.retainedBytes()).toBe(81)
  const iterator = stream[Symbol.asyncIterator]()
  expect((await iterator.next()).value.value).toBe('first')
  expect((await iterator.next()).value).toMatchObject({ kind: 'terminal', reason: 'overflow', droppedBytes: 10 })
  expect(quota.retainedBytes()).toBe(0)
  reader.close()
})

test.each(['latest', 'drop-oldest'])('%s replacement projects and retains the new aggregate size', async policy => {
  const stream = new CoreBoundedStream(limits, policy)
  const quota = new AggregateStreamQuota(200)
  quota.register(stream)
  quota.emit(stream, 'old', 20, 'peer', 0, 70)
  expect(quota.emit(stream, 'new', 20, 'peer', 0, 100).accepted).toBe(true)
  expect(quota.retainedBytes()).toBe(101)
  const reader = stream.claimConsumer()
  expect((await reader.next()).item.kind).toBe('overflow')
  const claim = (await reader.next()).claim
  expect(claim.item.value).toBe('new')
  expect(stream.claimedBytes(claim)).toBe(100)
  claim.commit()
  reader.close()
  await stream.close()
  stream.dispose()
  expect(quota.retainedBytes()).toBe(0)
})

test('a shared retained backing can charge less than its logical delivery payload', async () => {
  const stream = new CoreBoundedStream(limits, 'error')
  const quota = new AggregateStreamQuota(100)
  quota.register(stream)
  expect(quota.emit(stream, 'value', 10, null, 10, 5).accepted).toBe(true)
  expect(quota.retainedBytes()).toBe(6)
  const iterator = stream[Symbol.asyncIterator]()
  expect((await iterator.next()).value).toMatchObject({ kind: 'value', value: 'value' })
  expect(quota.retainedBytes()).toBe(1)
  await stream.close()
  await iterator.next()
  expect(quota.retainedBytes()).toBe(0)
})
