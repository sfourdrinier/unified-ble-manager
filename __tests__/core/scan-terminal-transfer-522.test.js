const { CoreBoundedStream } = require('../../src/core/bounded-stream')
const { AggregateStreamQuota } = require('../../src/core/aggregate-stream-quota')
const { resourceCount } = require('../../src/backend-contract/primitives')

const limits = { itemCapacity: resourceCount(4), byteCapacity: resourceCount(256), reservedControlCapacity: resourceCount(1) }
const failure = { code: 'platform.failure', domain: 'scan', operation: 'scan', retryability: 'never', platform: { domain: 'native', code: 'failure', safeMessage: 'original detail', metadata: {} } }

test('terminal transfer refuses atomically and succeeds on capacity release while preserving FIFO and cause', async () => {
  const size = Buffer.byteLength(JSON.stringify(failure))
  const quota = new AggregateStreamQuota(2 * size + 2)
  const source = new CoreBoundedStream(limits, 'error')
  const first = new CoreBoundedStream(limits, 'error')
  const second = new CoreBoundedStream(limits, 'error')
  for (const stream of [source, first, second]) quota.register(stream)
  quota.emit(first, 'prefix', 2)
  source.finishWithReason('source-failed', failure)
  const reader = source.claimConsumer({ retainTerminal: true })
  const claim = (await reader.next()).claim
  const before = quota.retainedBytes()
  expect(quota.transferTerminal(source, claim, [first, second])).toBe(false)
  expect(quota.retainedBytes()).toBe(before)
  expect(source.claimedTerminalBytes(claim)).toBe(size)
  expect(first.terminalReason()).toBeNull()
  const firstReader = first[Symbol.asyncIterator]()
  expect((await firstReader.next()).value.value).toBe('prefix')
  expect(quota.transferTerminal(source, claim, [first, second])).toBe(true)
  expect(quota.retainedBytes()).toBeLessThanOrEqual(2 * size + 2)
  expect((await firstReader.next()).value).toMatchObject({ kind: 'terminal', reason: 'source-failed', error: failure })
  expect((await second[Symbol.asyncIterator]().next()).value).toMatchObject({ kind: 'terminal', reason: 'source-failed', error: failure })
  expect(() => claim.rollback()).toThrow()
  reader.close()
})

test('terminal transfer charges every registered owner of a tracked destination view', async () => {
  const size = Buffer.byteLength(JSON.stringify(failure))
  const quota = new AggregateStreamQuota(2 * size + 2)
  const source = new CoreBoundedStream(limits, 'error')
  const destination = new CoreBoundedStream(limits, 'error')
  const viewOwner = new CoreBoundedStream(limits, 'error')
  quota.register(source)
  quota.register(destination)
  quota.register(viewOwner)
  viewOwner.trackRetainedView(destination)
  source.finishWithReason('source-failed', failure)
  const reader = source.claimConsumer({ retainTerminal: true })
  const claim = (await reader.next()).claim
  expect(quota.transferTerminal(source, claim, [destination])).toBe(false)
  expect(source.claimedTerminalBytes(claim)).toBe(size)
  reader.close()
})

test('cleanup failure reports committed transfer and leaves every terminal readable', async () => {
  const quota = new AggregateStreamQuota(2000)
  const source = new CoreBoundedStream(limits, 'error')
  const destination = new CoreBoundedStream(limits, 'error')
  quota.register(source)
  quota.register(destination)
  source.finishWithReason('source-failed', failure)
  const cleanup = new Error('source cleanup failed')
  source.onRetainedValuesDrained(() => { throw cleanup })
  const reader = source.claimConsumer({ retainTerminal: true })
  const claim = (await reader.next()).claim
  expect(() => quota.transferTerminal(source, claim, [destination])).toThrow('Stream terminal transferred')
  expect((await destination[Symbol.asyncIterator]().next()).value.error).toBe(failure)
  expect(() => claim.rollback()).toThrow()
  reader.close()
})

test('cancelling a refused claim permits a new reader to retry the exact terminal', async () => {
  const size = Buffer.byteLength(JSON.stringify(failure))
  const quota = new AggregateStreamQuota(2 * size + 2)
  const source = new CoreBoundedStream(limits, 'error')
  const first = new CoreBoundedStream(limits, 'error')
  const second = new CoreBoundedStream(limits, 'error')
  for (const stream of [source, first, second]) quota.register(stream)
  quota.emit(first, 'held', 2)
  source.finishWithReason('source-failed', failure)
  const abandonedReader = source.claimConsumer({ retainTerminal: true })
  const abandoned = (await abandonedReader.next()).claim
  expect(quota.transferTerminal(source, abandoned, [first, second])).toBe(false)
  abandonedReader.close()
  expect(() => abandoned.commit()).toThrow()
  const retryReader = source.claimConsumer({ retainTerminal: true })
  const retry = (await retryReader.next()).claim
  expect(retry.item).toBe(abandoned.item)
  expect((await first[Symbol.asyncIterator]().next()).value.value).toBe('held')
  expect(quota.transferTerminal(source, retry, [first, second])).toBe(true)
  expect((await first[Symbol.asyncIterator]().next()).value.error).toBe(failure)
  expect((await second[Symbol.asyncIterator]().next()).value.error).toBe(failure)
  retryReader.close()
})

test('invalid destination sets leave the source claim and destination untouched', async () => {
  const quota = new AggregateStreamQuota(2000)
  const source = new CoreBoundedStream(limits, 'error')
  const destination = new CoreBoundedStream(limits, 'error')
  quota.register(source)
  quota.register(destination)
  source.finishWithReason('source-failed', failure)
  const reader = source.claimConsumer({ retainTerminal: true })
  const claim = (await reader.next()).claim
  const before = quota.retainedBytes()
  expect(() => quota.transferTerminal(source, claim, [destination, destination])).toThrow()
  expect(() => quota.transferTerminal(source, claim, [source])).toThrow()
  expect(quota.retainedBytes()).toBe(before)
  expect(destination.terminalReason()).toBeNull()
  claim.rollback()
  reader.close()
})
